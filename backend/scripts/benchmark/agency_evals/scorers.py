"""Deterministic scorers for the agency eval set. Pure functions, no network.

Each scorer takes (output, arg, task) and returns (passed, detail).
`run_checks` runs every scorer named in task["checks"].
"""

from __future__ import annotations

import re

AI_FOOTERS = ("sent using", "sent from chatgpt", "generated by", "as an ai", "as a language model", "i'm an ai", "i am an ai")
EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
NUMBER_RE = re.compile(r"(?<!\d)(?:\d{1,3}(?:,\d{3})+(?!\d)|\d+)(?:\.\d+)?")
BOLD_RE = re.compile(r"\*\*(.+?)\*\*", re.S)
PLACEHOLDER_RE = re.compile(r"\[[A-Za-z][^\]\n]{0,40}\](?!\()|\{\{.*?\}\}")


def _norm_number(raw: str) -> str:
    """Canonical form so '1,200', '1200.0' and '1200' compare equal."""
    text = raw.replace(",", "").rstrip(".")
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text


def extract_numbers(text: str) -> set[str]:
    return {_norm_number(m) for m in NUMBER_RE.findall(EMAIL_RE.sub(" ", text))}


def no_em_dash(output, arg, task):
    # U+2014 em dash and U+2013 en dash both read as AI punctuation to Dillon.
    bad = [c for c in ("—", "–") if c in output]
    return (not bad, "found dash" if bad else "ok")


def no_ai_footer(output, arg, task):
    low = output.lower()
    hits = [p for p in AI_FOOTERS if p in low]
    return (not hits, f"found {hits}" if hits else "ok")


def bold_kpis(output, arg, task):
    lo, hi = arg
    n = len(BOLD_RE.findall(output))
    return (lo <= n <= hi, f"{n} bold spans, want {lo}-{hi}")


def numbers_from_fixture(output, arg, task):
    """Every number in the output must appear in the fixture, the prompt or task allowed_numbers.

    Single digits without a % or $ are ignored (counts like "3 terms", list markers).
    """
    fixture = task.get("fixture", "")
    # Fixture CSV rows are comma-separated, so also read them with commas as separators.
    allowed = extract_numbers(fixture) | extract_numbers(fixture.replace(",", " ")) | extract_numbers(task.get("prompt", ""))
    allowed |= {_norm_number(str(n)) for n in task.get("allowed_numbers", [])}
    stripped = re.sub(r"(?m)^\s*\d+[.)]\s", "", output)  # numbered list markers
    bad = []
    for n in sorted(extract_numbers(stripped)):
        if n in allowed:
            continue
        if re.fullmatch(r"\d", n) and not re.search(rf"[$]{n}\b|\b{n}%", stripped):
            continue
        bad.append(n)
    return (not bad, f"not in fixture: {bad}" if bad else "ok")


def required_cc(output, arg, task):
    cc_lines = " ".join(line.lower() for line in output.splitlines() if line.strip().lstrip("*_ ").lower().startswith("cc"))
    missing = [a for a in arg if a.lower() not in cc_lines]
    return (not missing, f"missing cc {missing}" if missing else "ok")


def max_chars(output, arg, task):
    return (len(output) <= arg, f"{len(output)} chars, cap {arg}")


def max_words(output, arg, task):
    n = len(output.split())
    return (n <= arg, f"{n} words, cap {arg}")


def must_include(output, arg, task):
    low = output.lower()
    missing = [t for t in arg if t.lower() not in low]
    return (not missing, f"missing {missing}" if missing else "ok")


def must_include_any(output, arg, task):
    """arg is a list of groups; each group needs at least one hit."""
    low = output.lower()
    missing = [g for g in arg if not any(t.lower() in low for t in g)]
    return (not missing, f"no hit for groups {missing}" if missing else "ok")


def must_not_include(output, arg, task):
    low = output.lower()
    hits = [t for t in arg if t.lower() in low]
    return (not hits, f"found {hits}" if hits else "ok")


def no_placeholders(output, arg, task):
    hits = PLACEHOLDER_RE.findall(output)
    return (not hits, f"placeholders {hits}" if hits else "ok")


def first_line_is(output, arg, task):
    first = next((ln.strip() for ln in output.splitlines() if ln.strip()), "")
    word = re.sub(r"^[^A-Za-z]+", "", first).split(" ")[0].strip(".:,*").upper() if first else ""
    return (word == arg.upper(), f"first word {word!r}, want {arg}")


def not_negated(output, arg, task):
    """Terms that converted must not be recommended as negatives."""
    bad = []
    for line in output.splitlines():
        low = line.lower()
        if re.search(r"negative|exclude|block", low) and not re.search(r"keep|don't|do not|not |leave|never", low):
            bad += [t for t in arg if t.lower() in low]
    return (not bad, f"negated converting terms {sorted(set(bad))}" if bad else "ok")


def ad_lines(output, arg, task):
    """arg: {"Headline": {"max": 30, "count": 3}, ...}. Lines look like 'Headline 1: text'."""
    problems = []
    for label, rule in arg.items():
        texts = [m.group(1).strip() for m in re.finditer(rf"(?im)^\W*{re.escape(label)}\s*\d*\s*:\s*(.+)$", output)]
        if len(texts) != rule["count"]:
            problems.append(f"{label}: {len(texts)} lines, want {rule['count']}")
        problems += [f"{label} {len(t)}>{rule['max']}: {t[:30]}" for t in texts if len(t) > rule["max"]]
    return (not problems, "; ".join(problems) if problems else "ok")


SCORERS = {
    "no_em_dash": no_em_dash,
    "no_ai_footer": no_ai_footer,
    "bold_kpis": bold_kpis,
    "numbers_from_fixture": numbers_from_fixture,
    "required_cc": required_cc,
    "max_chars": max_chars,
    "max_words": max_words,
    "must_include": must_include,
    "must_include_any": must_include_any,
    "must_not_include": must_not_include,
    "no_placeholders": no_placeholders,
    "first_line_is": first_line_is,
    "not_negated": not_negated,
    "ad_lines": ad_lines,
}


def run_checks(output: str, task: dict) -> list[dict]:
    results = []
    for name, arg in task.get("checks", {}).items():
        passed, detail = SCORERS[name](output, arg, task)
        results.append({"name": name, "passed": bool(passed), "detail": detail})
    return results

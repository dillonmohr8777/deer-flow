def test_task_file_is_valid_sanitized_and_balanced():
    tasks = runner.load_tasks()
    assert 20 <= len(tasks) <= 30
    cats = {t["category"] for t in tasks}
    assert cats == {"weekly_report_email", "slack_reply", "search_term_review", "kpi_summary", "followup_email", "ad_copy", "fact_check"}
    blob = json.dumps(tasks)
    assert all(d.rstrip(".") == "example.com" for d in re.findall(r"@([\w.-]+)", blob)), "only example.com addresses allowed"
    for t in tasks:
        assert t["synthetic"] is True
        assert t["checks"] and set(t["checks"]) <= set(scorers.SCORERS)
        assert t["checks"].get("no_em_dash") and t["checks"].get("no_ai_footer")


def test_duplicate_ids_rejected(tmp_path):
    p = tmp_path / "t.jsonl"
    p.write_text('{"id":"a"}\n{"id":"a"}\n')
    with pytest.raises(ValueError):
        runner.load_tasks(p)


def test_clean_reference_answer_passes_a_report_task():
    task = next(t for t in runner.load_tasks() if t["id"] == "report-01")
    answer = (
        "Subject: Weekly report for Acme Plumbing\nTo: Pat\nCc: sean@example.com, mac@example.com, melissa@example.com\n\n"
        "Hey Pat, here's this week's update for Acme Plumbing.\n\n**41 leads** (up from 34), **$38.20 cost per lead** (down from $44.10), **17 booked jobs** (up from 12).\n\n"
        f"Full report: {task['fixture'].split('Report URL: ')[1].splitlines()[0]}\n\nDillon"
    )
    res = runner.score_task(task, answer)
    assert res["passed"], [c for c in res["checks"] if not c["passed"]]


# ---- results math ----


def test_task_cost_prefers_reported_cost():
    assert runner.task_cost({"cost": 0.002, "prompt_tokens": 10**6}, 5, 5) == 0.002
    assert runner.task_cost({"prompt_tokens": 1_000_000, "completion_tokens": 500_000}, 2.0, 4.0) == pytest.approx(4.0)
    assert runner.task_cost({}, 2.0, 4.0) == 0.0


def test_compute_totals():
    rows = [
        {"category": "a", "passed": True, "cost": 0.01, "prompt_tokens": 10, "completion_tokens": 5},
        {"category": "a", "passed": False, "cost": 0.03, "prompt_tokens": 20, "completion_tokens": 5, "error": "boom"},
        {"category": "b", "passed": True, "cost": 0.02, "prompt_tokens": 30, "completion_tokens": 10},
    ]
    t = runner.compute_totals(rows)
    assert (t["tasks"], t["passed"], t["errors"]) == (3, 2, 1)
    assert t["pass_rate"] == pytest.approx(2 / 3)
    assert t["cost"] == pytest.approx(0.06)
    assert t["cost_per_task"] == pytest.approx(0.02)
    assert (t["prompt_tokens"], t["completion_tokens"]) == (60, 20)
    assert t["by_category"]["a"]["pass_rate"] == 0.5
    assert runner.compute_totals([])["pass_rate"] == 0.0


# ---- runner with a fake endpoint, no network ----


class FakeResp:
    def __init__(self, text):
        self.text = text

    def raise_for_status(self):
        pass

    def json(self):
        return {"choices": [{"message": {"content": self.text}}], "usage": {"prompt_tokens": 100, "completion_tokens": 20, "cost": 0.001}}


class FakeClient:
    def __init__(self):
        self.calls = []

    def post(self, url, json, headers, timeout):
        self.calls.append((url, json["model"], json["messages"][1]["content"]))
        return FakeResp("Sent using Claude — bad")


def test_run_writes_results_and_never_stores_key(tmp_path, monkeypatch):
    monkeypatch.setenv("FAKE_KEY", "sk-secret-value")
    out = tmp_path / "r.json"
    client = FakeClient()
    doc = runner.run("m/x", "https://example.test/v1", "FAKE_KEY", out, runner.load_tasks()[:3], client=client, workers=1)
    assert client.calls[0][0] == "https://example.test/v1/chat/completions"
    assert "DATA:" in client.calls[0][2]
    assert doc["totals"]["tasks"] == 3 and doc["totals"]["passed"] == 0
    assert doc["totals"]["cost"] == pytest.approx(0.003)
    saved = out.read_text()
    assert "sk-secret-value" not in saved and json.loads(saved)["model"] == "m/x"


def test_run_requires_key(tmp_path, monkeypatch):
    monkeypatch.delenv("NOPE_KEY", raising=False)

"""Offline unit tests for scripts/benchmark/agency_evals (scorers, task file, results math, report)."""

from __future__ import annotations

import json
import re

import pytest

from scripts.benchmark.agency_evals import report, runner, scorers

TASK = {"fixture": "Leads | 41 | 34\nSpend | $1,566", "prompt": "write it", "checks": {}}


def ok(name, output, arg=True, task=TASK):
    return scorers.SCORERS[name](output, arg, task)[0]


def test_no_em_dash():
    assert ok("no_em_dash", "plain text - with hyphen")
    assert not ok("no_em_dash", "bad — dash")
    assert not ok("no_em_dash", "range 1–2")


def test_no_ai_footer():
    assert ok("no_ai_footer", "Talk soon, Dillon")
    for bad in ("Sent using Claude", "Generated by a bot", "As an AI, I", "sent from ChatGPT"):
        assert not ok("no_ai_footer", bad)


def test_bold_kpis_range():
    assert ok("bold_kpis", "**a** **b** **c**", (3, 5))
    assert not ok("bold_kpis", "**a** **b**", (3, 5))
    assert not ok("bold_kpis", " ".join(f"**k{i}**" for i in range(6)), (3, 5))


def test_numbers_from_fixture():
    assert ok("numbers_from_fixture", "Leads went from 34 to 41 and spend was $1,566.")
    assert ok("numbers_from_fixture", "spend was 1566")  # comma-insensitive
    assert not ok("numbers_from_fixture", "Leads hit 99.")
    assert ok("numbers_from_fixture", "We saw 3 things.")  # bare single digits ignored
    assert not ok("numbers_from_fixture", "CTR was 7%.")  # percents are not ignored
    assert ok("numbers_from_fixture", "1. Leads 41\n2. Spend 1566")  # list markers
    assert ok("numbers_from_fixture", "email a2@example.com about 41")  # addresses stripped
    assert ok("numbers_from_fixture", "CPL is 38.2", task=TASK | {"allowed_numbers": [38.20]})
    assert not ok("numbers_from_fixture", "CPL is 38.2")


def test_required_cc():
    assert ok("required_cc", "Subject: hi\nCc: a@example.com, b@example.com", ["a@example.com", "B@example.com"])
    assert not ok("required_cc", "Subject: hi\nCc: a@example.com", ["a@example.com", "b@example.com"])
    assert not ok("required_cc", "Body mentions a@example.com but no cc line", ["a@example.com"])


def test_length_caps():
    assert ok("max_chars", "abc", 3)
    assert not ok("max_chars", "abcd", 3)
    assert ok("max_words", "one two three", 3)
    assert not ok("max_words", "one two three four", 3)


def test_include_exclude():
    assert ok("must_include", "Hello Acme", ["acme"])
    assert not ok("must_include", "Hello", ["acme"])
    assert ok("must_include_any", "negate jobs", [["jobs", "hiring"], ["negate"]])
    assert not ok("must_include_any", "negate", [["jobs", "hiring"]])
    assert ok("must_not_include", "fine", ["Dear"])
    assert not ok("must_not_include", "Dear Pat", ["dear"])


def test_numbers_csv_rows():
    task = TASK | {"fixture": "Oct 5,1100,24,700"}
    assert ok("numbers_from_fixture", "spend 1100 and 24 leads, 700 clicks", task=task)
    assert ok("numbers_from_fixture", "spend $1,100", task=task)


def test_no_placeholders():
    assert ok("no_placeholders", "[View the report](https://example.com/r)")
    assert ok("no_placeholders", "Hi Pat")
    assert not ok("no_placeholders", "Hi [Name]")
    assert not ok("no_placeholders", "Hi {{name}}")


def test_first_line_is():
    assert ok("first_line_is", "FALSE\nbecause", "FALSE")
    assert ok("first_line_is", "**True.** yes", "TRUE")
    assert not ok("first_line_is", "The claim is false", "FALSE")
    assert not ok("first_line_is", "", "FALSE")


def test_not_negated():
    out = "Add as negative: free classes\nKeep: emergency plumber (5 conversions)"
    assert ok("not_negated", out, ["emergency plumber"])
    assert not ok("not_negated", "Negative keyword: emergency plumber", ["emergency plumber"])
    assert ok("not_negated", "Do not negate emergency plumber, it converted", ["emergency plumber"])


def test_ad_lines():
    rules = {"Headline": {"max": 30, "count": 2}, "Description": {"max": 20, "count": 1}}
    good = "Headline 1: Fast plumbers\nHeadline 2: Call today\nDescription 1: We fix leaks fast"
    assert ok("ad_lines", good, rules)
    assert not ok("ad_lines", good.replace("Fast plumbers", "x" * 31), rules)
    assert not ok("ad_lines", good + "\nHeadline 3: extra", rules)
    assert not ok("ad_lines", good.replace("We fix leaks fast", "y" * 21), rules)


def test_run_checks_aggregates():
    task = TASK | {"checks": {"no_em_dash": True, "max_words": 2}}
    res = scorers.run_checks("a b c", task)
    assert [(c["name"], c["passed"]) for c in res] == [("no_em_dash", True), ("max_words", False)]



def test_report_renders_trend_and_escapes(tmp_path):
    def doc(rate_pass, when):
        rows = [{"id": "t<1>", "category": "c", "passed": bool(rate_pass), "checks": [{"name": "n", "passed": bool(rate_pass), "detail": "d<x>"}], "output": "<script>x</script>", "cost": 0.01}]
        return {"model": "m", "started_at": when, "totals": runner.compute_totals(rows), "results": rows}

    a, b = tmp_path / "a.json", tmp_path / "b.json"
    a.write_text(json.dumps(doc(0, "2026-10-05T00:00:00")))
    b.write_text(json.dumps(doc(1, "2026-10-12T00:00:00")))
    out = tmp_path / "r.html"
    report.build_report([a, b], out)
    html = out.read_text()
    assert "<script>x</script>" not in html and "&lt;script&gt;" in html
    assert "2026-10-05T00:00:00" in html and "100%" in html and "0%" in html

#!/bin/sh
# One-command release (from desktop/):
#   MOMOBOT_SITE_URL=https://<download-site>/ MOMOBOT_SITE_DIR=<site folder> \
#   MOMOBOT_WORKSPACE=https://<host>/workspace npm run release
# Checks, packages and smoke-tests the committed source, tags momobot-desktop-v<version>, uploads
# the build to that fixed tag (never marked GitHub "latest"; nothing reads "latest"), then writes
# the update channel into MOMOBOT_SITE_DIR: release.json, install.sh and a setup.sh that pins this
# tag plus the SHA-256 of the ZIP and of install.sh. Deploying that folder is what ships the
# update to teammates, so deploy it only once approved.
# ponytail: builds on this Mac because GitHub Actions is stalled on this account; move
# these steps into a tag-triggered workflow once Actions runs again.
set -eu
cd "$(dirname "$0")/.."
site=${MOMOBOT_SITE_URL:?set MOMOBOT_SITE_URL (download site, ends with /)}
site_dir=${MOMOBOT_SITE_DIR:?set MOMOBOT_SITE_DIR (local download-site folder)}
workspace=${MOMOBOT_WORKSPACE:?set MOMOBOT_WORKSPACE (https://host/workspace)}
case "$site" in https://*/) ;; *) echo "MOMOBOT_SITE_URL must be https and end with /" >&2; exit 1 ;; esac
case "$workspace" in *[\"\\\ \'\`\$?#]*|"") echo "MOMOBOT_WORKSPACE has invalid characters" >&2; exit 1 ;; https://*) ;; *) echo "MOMOBOT_WORKSPACE must be https" >&2; exit 1 ;; esac
version=$(node -p "require('./package.json').version")
tag="momobot-desktop-v$version"
if [ -n "$(git status --porcelain -- .)" ]; then echo "Commit the desktop changes first." >&2; exit 1; fi
if git ls-remote --exit-code --tags origin "refs/tags/$tag" >/dev/null 2>&1; then echo "$tag is already released; bump the version." >&2; exit 1; fi
repo=$(gh repo view "$(git remote get-url origin)" --json nameWithOwner -q .nameWithOwner)
base="https://github.com/$repo/releases/download/$tag"

npm run check
npm test
out=$(mktemp -d)
trap 'rm -rf "$out"' EXIT
MOMOBOT_RELEASE_DIR="$out" npm run package:mac
build=$(ls -d "$out"/build-*)
app=$(node -p "require('$build/build-paths.json').appPath")
"$app/Contents/MacOS/MomoBot" --smoke-test > "$out/smoke.json" || true
grep -q '"passed":true' "$out/smoke.json" || { echo "Launch smoke failed; nothing released:" >&2; cat "$out/smoke.json" >&2; exit 1; }
zip_sha=$(shasum -a 256 "$build/MomoBot-mac-arm64.zip" | awk '{print $1}')
install_sha=$(shasum -a 256 "$build/install.sh" | awk '{print $1}')

git tag -a "$tag" -m "MomoBot desktop $version"
git push origin "$tag"
# shellcheck disable=SC2016 # the backticks are Markdown, not a command
printf 'MomoBot desktop %s for Apple Silicon Macs (ad-hoc signed, not notarized).\n\nInstall or update with the setup line on the team download page; it pins this SHA-256:\n\n```\n%s  MomoBot-mac-arm64.zip\n```\n' "$version" "$zip_sha" > "$out/notes.md"
gh release create "$tag" --repo "$repo" --latest=false --title "MomoBot desktop $version" --notes-file "$out/notes.md" \
  "$build/MomoBot-mac-arm64.zip" "$build/MomoBot-mac-arm64.dmg" "$build/SHA256SUMS" "$build/release.json" "$build/install.sh" \
  || { git push origin ":refs/tags/$tag"; git tag -d "$tag"; echo "Release upload failed; tag removed so a rerun works." >&2; exit 1; }

mkdir -p "$site_dir"
cp "$build/release.json" "$build/install.sh" "$site_dir/"
cat > "$site_dir/setup.sh" <<EOF
#!/bin/sh
# MomoBot $version internal setup (generated by release.sh). Installs or updates the desktop app
# from the pinned GitHub release $tag, refusing any ZIP or installer whose SHA-256 does not match.
set -eu
main() {
  tmp=\$(mktemp -d)
  trap 'rm -rf "\$tmp"' EXIT
  curl -fsSL ${site}install.sh -o "\$tmp/install.sh"
  echo "$install_sha  \$tmp/install.sh" | shasum -a 256 -c - >/dev/null || { echo "Installer checksum mismatch; nothing installed." >&2; exit 1; }
  sh "\$tmp/install.sh" $base --sha256 $zip_sha --workspace $workspace --update-url $site
}
main "\$@"
EOF
echo "Released $tag (zip sha256 $zip_sha). Channel files written to $site_dir; deploy that folder to ship it."
